// Builds migrations/0002_seed_journal.sql from content/blog/*.md
// Usage: node scripts/build-blog-seed.mjs
// Posts are inserted with ON CONFLICT DO NOTHING, so edits made later in the dashboard are never overwritten.
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = "content/blog";
const q = (s) => (s == null ? "NULL" : `'${String(s).replace(/'/g, "''")}'`);

const rows = readdirSync(dir)
  .filter((f) => f.endsWith(".md"))
  .sort()
  .map((f) => {
    const raw = readFileSync(join(dir, f), "utf8");
    const m = raw.match(/^---\n([\s\S]*?)\n---\n([\s\S]*)$/);
    if (!m) throw new Error(`Missing front matter: ${f}`);
    const meta = Object.fromEntries(
      m[1].split("\n").map((l) => {
        const i = l.indexOf(":");
        return [l.slice(0, i).trim(), l.slice(i + 1).trim().replace(/^"(.*)"$/, "$1")];
      })
    );
    for (const k of ["title", "slug", "excerpt", "cover", "published"]) if (!meta[k]) throw new Error(`${f}: missing ${k}`);
    return { ...meta, body: m[2].trim() };
  });

const sql = [
  "-- Seed Journal posts (generated by scripts/build-blog-seed.mjs — edit content/blog/*.md and re-run)",
  ...rows.map(
    (r) =>
      `INSERT INTO posts (slug, title, excerpt, body, cover, status, created_at, updated_at, published_at) VALUES (${q(r.slug)}, ${q(r.title)}, ${q(r.excerpt)}, ${q(r.body)}, ${q(r.cover)}, 'published', ${q(r.published)}, ${q(r.published)}, ${q(r.published)}) ON CONFLICT(slug) DO NOTHING;`
  ),
].join("\n\n");

writeFileSync("migrations/0002_seed_journal.sql", sql + "\n");
console.log(`Wrote ${rows.length} posts to migrations/0002_seed_journal.sql`);
